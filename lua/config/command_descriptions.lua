function M.annotate(items, is_command)
  if not is_command then
    return items
  end
  local user_commands = vim.api.nvim_get_commands({ builtin = false })
  for _, item in ipairs(items) do
    local desc = descriptions[item.label]
    if not desc then
      local command = user_commands[item.label]
      local user_desc = command and command.definition
      if user_desc and user_desc:find("[\128-\255]") then
        desc = user_desc
      end
    end
    local help = ":help :" .. item.label
    desc = desc or ("详细用法见 " .. help)
    item.labelDetails = vim.tbl_extend("force", item.labelDetails or {}, { description = desc })
    item.documentation = { kind = "markdown", value = "**:" .. item.label .. "**\n\n" .. desc .. "\n\n帮助：`" .. help .. "`" }
  end
  return items
end

